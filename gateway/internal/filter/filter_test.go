package filter

import (
	"strings"
	"testing"
)

func TestByPath(t *testing.T) {
	skip := []string{
		"package-lock.json", "web/yarn.lock", "go.sum", "vendor/github.com/x/y.go", "app/node_modules/a/index.js",
		"dist/app.js", "assets/logo.png", "static/app.min.js", "api/v1/service.pb.go",
	}
	for _, p := range skip {
		if ByPath(p) == "" {
			t.Errorf("%s should be skipped", p)
		}
	}
	keep := []string{"main.go", "src/build.ts", "lib/distance.py", "cmd/server/main.go"}
	for _, p := range keep {
		if r := ByPath(p); r != "" {
			t.Errorf("%s should be reviewed, got %q", p, r)
		}
	}
}

func TestByStatus(t *testing.T) {
	if ByStatus("removed", "@@ -1 +0,0 @@\n-a", 1, 100) == "" {
		t.Error("removed files are skipped")
	}
	if ByStatus("modified", "", 0, 100) == "" {
		t.Error("files without a patch are skipped")
	}
	if ByStatus("modified", "@@ -1 +1 @@\n+a", 2000, 1500) == "" {
		t.Error("oversized patches are skipped")
	}
	if r := ByStatus("modified", "@@ -1 +1 @@\n+a", 2, 1500); r != "" {
		t.Errorf("normal file skipped: %q", r)
	}
}

func TestByContent(t *testing.T) {
	if ByContent([]byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n")) == "" {
		t.Error("generated banner not detected")
	}
	if ByContent([]byte{'a', 0, 'b'}) == "" {
		t.Error("binary not detected")
	}
	if ByContent([]byte(strings.Repeat("var a=1;", 1000))) == "" {
		t.Error("minified not detected")
	}
	if r := ByContent([]byte("package main\n\nfunc main() {}\n")); r != "" {
		t.Errorf("normal file flagged: %q", r)
	}
}
