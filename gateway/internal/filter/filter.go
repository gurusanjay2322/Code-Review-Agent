package filter

import (
	"bytes"
	"path"
	"strings"
)

var lockfiles = map[string]bool{
	"package-lock.json": true, "npm-shrinkwrap.json": true, "yarn.lock": true, "pnpm-lock.yaml": true,
	"bun.lockb": true, "bun.lock": true, "go.sum": true, "cargo.lock": true, "poetry.lock": true,
	"pipfile.lock": true, "composer.lock": true, "gemfile.lock": true, "podfile.lock": true,
	"packages.lock.json": true, "flake.lock": true, "uv.lock": true,
}

var skippedDirs = []string{
	"vendor/", "node_modules/", "dist/", "build/", "out/", ".next/", "coverage/",
	"__snapshots__/", "third_party/", ".yarn/",
}

var binaryExts = map[string]bool{
	".png": true, ".jpg": true, ".jpeg": true, ".gif": true, ".webp": true, ".ico": true, ".bmp": true,
	".svg": true, ".pdf": true, ".zip": true, ".gz": true, ".tgz": true, ".tar": true, ".7z": true,
	".woff": true, ".woff2": true, ".ttf": true, ".otf": true, ".eot": true, ".mp3": true, ".mp4": true,
	".mov": true, ".wav": true, ".jar": true, ".exe": true, ".dll": true, ".so": true, ".dylib": true,
	".class": true, ".pyc": true, ".wasm": true, ".bin": true, ".map": true, ".snap": true, ".lockb": true,
}

var generatedSuffixes = []string{
	".min.js", ".min.css", ".min.mjs", ".bundle.js", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".pb.ts",
	"_generated.go", ".generated.ts", ".generated.js", ".g.dart", ".freezed.dart", ".designer.cs",
}

// ByPath decides from the file name alone. reason is empty when the file should be reviewed.
func ByPath(p string) string {
	lower := strings.ToLower(p)
	base := path.Base(lower)
	if lockfiles[base] || strings.HasSuffix(base, ".lock") {
		return "lockfile"
	}
	for _, dir := range skippedDirs {
		if strings.HasPrefix(lower, dir) || strings.Contains(lower, "/"+dir) {
			return "vendored or build output (" + strings.TrimSuffix(dir, "/") + ")"
		}
	}
	if binaryExts[path.Ext(base)] {
		return "binary or asset file"
	}
	for _, s := range generatedSuffixes {
		if strings.HasSuffix(base, s) {
			if strings.Contains(s, ".min.") {
				return "minified file"
			}
			return "generated file"
		}
	}
	return ""
}

// ByStatus decides from GitHub's file metadata.
func ByStatus(status, patch string, patchLines, maxPatchLines int) string {
	switch {
	case status == "removed":
		return "file removed"
	case strings.TrimSpace(patch) == "":
		if status == "renamed" {
			return "renamed without changes"
		}
		return "no textual diff (binary or too large)"
	case maxPatchLines > 0 && patchLines > maxPatchLines:
		return "diff too large"
	}
	return ""
}

var generatedMarkers = [][]byte{
	[]byte("code generated"), []byte("do not edit"), []byte("@generated"), []byte("autogenerated"),
	[]byte("auto-generated"), []byte("this file is generated"),
}

// ByContent inspects the head of the file for binary data, generated-code banners, and minification.
func ByContent(content []byte) string {
	head := content
	if len(head) > 8192 {
		head = head[:8192]
	}
	if bytes.IndexByte(head, 0) >= 0 {
		return "binary file"
	}
	lowerHead := bytes.ToLower(firstLines(head, 10))
	for _, m := range generatedMarkers {
		if bytes.Contains(lowerHead, m) {
			return "generated file"
		}
	}
	lines := bytes.Count(content, []byte("\n")) + 1
	if len(content) > 2000 && len(content)/lines > 300 {
		return "minified file"
	}
	return ""
}

func firstLines(b []byte, n int) []byte {
	idx := 0
	for i := 0; i < n; i++ {
		j := bytes.IndexByte(b[idx:], '\n')
		if j < 0 {
			return b
		}
		idx += j + 1
	}
	return b[:idx]
}
